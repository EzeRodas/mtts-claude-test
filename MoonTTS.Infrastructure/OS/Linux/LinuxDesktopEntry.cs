using System.Text;
using MoonTTS.Domain.Common;

namespace MoonTTS.Infrastructure.OS.Linux;

/* File Structure:
        - EnsureInstalled(string appId) : Result<bool>
        - FindExistingEntry(string fileName) : string?
        - GetDataHome() : string
        - GetDataDirs() : IEnumerable<string>
        - BuildEntryContent(IReadOnlyList<string> command) : string
        - GetLaunchCommand() : IReadOnlyList<string>?
        - QuoteExecArgument(string argument) : string
*/

/* Provisions the freedesktop `.desktop` entry that identifies Moon-TTS to the XDG Desktop Portal.
   Unsandboxed (host) apps register their app ID through `org.freedesktop.host.portal.Registry.Register`, and the
   portal only accepts the ID if a matching `<appId>.desktop` file exists in the XDG data directories. Without it
   the registration fails with "App info not found" and the GlobalShortcuts portal rejects the session with
   "An app id is required". Entries installed by a package or written by the user are never touched; only the
   entry generated by this class (marked with `X-MoonTTS-Generated`) gets refreshed when the binary moves. */

public static class LinuxDesktopEntry
{
    private const string GeneratedMarker = "X-MoonTTS-Generated=true";

    /* Makes sure `<appId>.desktop` exists. Returns true when the entry was (re)written by this call,
       false when an up-to-date or externally owned entry was already present */
    public static Result<bool> EnsureInstalled(string appId)
    {
        string fileName = $"{appId}.desktop";

        try
        {
            string? existingPath = FindExistingEntry(fileName);
            string? existingContent = existingPath != null ? File.ReadAllText(existingPath) : null;

            /* Entries owned by a package manager or the user take precedence and are left untouched */
            if (existingContent != null && !existingContent.Contains(GeneratedMarker, StringComparison.Ordinal))
                return Result<bool>.Success(false);

            IReadOnlyList<string>? command = GetLaunchCommand();
            if (command == null)
                return Result<bool>.Failure("Unable to resolve the executable path for the desktop entry.");

            string content = BuildEntryContent(command);
            string targetPath = Path.Combine(GetDataHome(), "applications", fileName);

            if (existingPath == targetPath && existingContent == content)
                return Result<bool>.Success(false);

            /* Atomic write so the portal never parses a half-written entry */
            Directory.CreateDirectory(Path.GetDirectoryName(targetPath)!);
            string tempPath = targetPath + ".tmp";
            File.WriteAllText(tempPath, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            File.Move(tempPath, targetPath, overwrite: true);

            return Result<bool>.Success(true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return Result<bool>.Failure($"Failed to install desktop entry '{fileName}': {ex.Message}", ex);
        }
    }

    /* Looks up the entry following the XDG lookup order (data home first, then data dirs) */
    private static string? FindExistingEntry(string fileName)
    {
        foreach (string dataDir in GetDataDirs().Prepend(GetDataHome()))
        {
            string candidate = Path.Combine(dataDir, "applications", fileName);
            if (File.Exists(candidate))
                return candidate;
        }
        return null;
    }

    /* Resolves $XDG_DATA_HOME, falling back to ~/.local/share as the spec defines */
    private static string GetDataHome()
    {
        string? dataHome = Environment.GetEnvironmentVariable("XDG_DATA_HOME");
        if (!string.IsNullOrEmpty(dataHome) && Path.IsPathRooted(dataHome))
            return dataHome;

        return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".local", "share");
    }

    /* Resolves $XDG_DATA_DIRS, falling back to /usr/local/share:/usr/share as the spec defines */
    private static IEnumerable<string> GetDataDirs()
    {
        string? dataDirs = Environment.GetEnvironmentVariable("XDG_DATA_DIRS");
        if (string.IsNullOrEmpty(dataDirs))
            dataDirs = "/usr/local/share:/usr/share";

        return dataDirs
            .Split(':', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Where(Path.IsPathRooted);
    }

    /* Builds the desktop entry body pointing at the running executable */
    private static string BuildEntryContent(IReadOnlyList<string> command)
    {
        var builder = new StringBuilder();
        builder.Append("[Desktop Entry]\n");
        builder.Append("Type=Application\n");
        builder.Append("Name=Moon-TTS\n");
        builder.Append("Comment=Local text-to-speech accessibility tool\n");
        builder.Append("Exec=").AppendJoin(' ', command.Select(QuoteExecArgument)).Append('\n');
        builder.Append("Terminal=false\n");
        builder.Append("Categories=Utility;Accessibility;\n");
        builder.Append(GeneratedMarker).Append('\n');
        return builder.ToString();
    }

    /* Returns the command line that relaunches the current process (native/apphost binary, or `dotnet <dll>`) */
    private static IReadOnlyList<string>? GetLaunchCommand()
    {
        string? processPath = Environment.ProcessPath;
        if (string.IsNullOrEmpty(processPath))
            return null;

        /* If running uncompiled from "dotnet" command, the entry assembly has to be passed to the host */
        if (Path.GetFileNameWithoutExtension(processPath).Equals("dotnet", StringComparison.OrdinalIgnoreCase))
        {
            string entryAssembly = Path.GetFullPath(Environment.GetCommandLineArgs()[0]);
            return [processPath, entryAssembly];
        }

        return [processPath];
    }

    /* Quotes an Exec argument following the Desktop Entry spec: reserved characters are backslash-escaped
       inside double quotes, then backslashes are escaped again at the string-value level, and '%' is doubled
       so it is not read as a field code */
    private static string QuoteExecArgument(string argument)
    {
        var quoted = new StringBuilder(argument.Length + 2);
        quoted.Append('"');
        foreach (char c in argument)
        {
            switch (c)
            {
                case '"' or '`' or '$':
                    quoted.Append('\\').Append(c);
                    break;
                case '\\':
                    quoted.Append(@"\\");
                    break;
                case '%':
                    quoted.Append("%%");
                    break;
                default:
                    quoted.Append(c);
                    break;
            }
        }
        quoted.Append('"');

        /* String-value level escaping: every backslash produced above is itself escaped, and control
           characters are written as escape sequences so the entry stays a single line */
        return quoted.ToString()
            .Replace(@"\", @"\\")
            .Replace("\n", @"\n")
            .Replace("\r", @"\r")
            .Replace("\t", @"\t");
    }
}
